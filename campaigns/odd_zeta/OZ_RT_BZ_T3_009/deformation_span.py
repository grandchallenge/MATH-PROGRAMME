def summed_hk(n: int) -> Fraction:
    total = Fraction(0)
    for k in range(n + 1):
        hk = harmonic(k)
        for l in range(n + 1):
            total += kernel(n, k, l) * hk
    return total


def rank_over_q(rows: list[list[int]]) -> int:
    a = [[Fraction(x) for x in row] for row in rows]
    if not a:
        return 0
    m, n = len(a), len(a[0])
    r = 0
    for c in range(n):
        pivot = next((i for i in range(r, m) if a[i][c]), None)
        if pivot is None:
            continue
        a[r], a[pivot] = a[pivot], a[r]
        q = a[r][c]
        a[r] = [x / q for x in a[r]]
        for i in range(m):
            if i != r and a[i][c]:
                q = a[i][c]
                a[i] = [x - q*y for x, y in zip(a[i], a[r])]
        r += 1
        if r == m:
            break
    return r


