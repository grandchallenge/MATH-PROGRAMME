def harmonic(m: int, r: int = 1) -> Fraction:
    return sum((Fraction(1, j**r) for j in range(1, m + 1)), Fraction(0))


def kernel(n: int, k: int, l: int) -> int:
    return (
        comb(n + k, n) * comb(n, k) ** 2
        * comb(n + l, n) * comb(n, l) ** 2
        * comb(n + k + l, n)
    )


